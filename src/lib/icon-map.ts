/** Names already reported, so a missing icon warns once and not on every render. */
const reported = new Set<string>()

/** The component for a kebab-case Lucide name. Unknown names get a neutral dashed square. */
export function lucideIcon(name: string): Component {
  const icon = icons[name]
  if (icon) return icon

  if (import.meta.env.DEV && !reported.has(name)) {
    reported.add(name)
    console.warn(`[icon-map] "${name}" is not in src/lib/icon-map.ts; add it there.`)
  }
  return SquareDashedIcon
}
