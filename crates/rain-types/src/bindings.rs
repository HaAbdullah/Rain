//! The TypeScript generator: one file with every declaration. Foundation sections 9.3 and 9.4.
//!
//! Generate:    `npm run types`        (cargo test -p rain-types write_single_file)
//! Drift check: `npm run types:check`  (the same test with RAIN_TYPES_CHECK=1)
//!
//! Why one file and not ts-rs's per-file export: with `#[ts(type = "...")]` on a field, the
//! per-file output loses the imports of the types it names. In one file nothing needs imports.
//!
//! Comments: ts-rs copies a `///` comment on a struct FIELD into the TypeScript file, at an awkward
//! place. So on the fields of generated structs use plain `//` comments. (A `///` on the type or on
//! an enum variant is not copied.)

use ts_rs::{Config, TS};

use crate::events::TOPIC_NAMES;

/// Writes `export <declaration>` for every listed type, each followed by a blank line.
macro_rules! declarations {
    ($config:expr; $($ty:ty),+ $(,)?) => {{
        let mut out = String::new();
        $(
            out.push_str("export ");
            out.push_str(&<$ty as TS>::decl($config));
            out.push_str("\n\n");
        )+
        out
    }};
}

/// The whole generated file. A type that is missing from the list below is not generated, and
/// then shows up as a TypeScript compile error where the frontend uses it.
pub fn single_file(config: &Config) -> String {
    use crate::*;
    let body = declarations!(config;
        // common
        Status, IconKind, IconRef, ErrorCode, ApiError,
        // stream
        Frame, Hello, ResyncReason, Resync, StopReason, LifecycleKind, Lifecycle,
        // system
        Ping, ConfigIssue, SourceState, SourceStatus, ShellStatus, Health,
        // settings
        ResetAfterSeconds, CountdownSeconds, MonitorClaudeState, Settings, SettingsPatch,
        // Each feature section adds its types under its own line below, and only there.
        // launcher and apps (section 01)
        SearchType, PinnableType, SearchItem, AppKind, AppEntry, PoolMember, Pool, PoolDraft, PinBody,
        LaunchType, LaunchMode, LaunchTarget, LaunchStep, RunStatus, LaunchRun,
        // projects and games (section 02)
        EnvKind, EnvStep, Project,
        LayoutZone, LayoutWhat, LayoutItem, LayoutScope, LayoutStepOption, ProjectLayout, LayoutSave,
        GameSource, Game, GameSourceStatus, GameLibrary, CustomGameDraft, GamePatch,
        // sessions, jobs and idle jobs (section 03)
        JobKind, JobSource, JobRun, LogLevel, LogLine, ScheduledJob, IdleState, IdleResource, IdleJob, EnabledBody,
        PermissionAnswer, PermissionRequest, SessionEventKind, SessionEvent, SessionHost, ClaudeSession,
        PermissionAnswerBody, PermissionAnswerResult, FocusKind, FocusResult,
        // life (section 04)
        Cadence, Habit, HabitDraft, HabitCell, HabitSummary, HabitDay, HabitStats, HabitTickBody,
        VaultStatus, PropertySuggestion, OpenNoteResult, CalendarEvent,
        // disk and machine (section 05)
        FileCategory, NodeKind, ScanStatus, Drive, DiskNode, DiskScan, MachineState, StartScanBody,
        RevealBody, PathsCheckBody, PathKind, PathCheck,
        // hardware (section 05)
        HardwareKind, HardwareLink, HardwareBattery, HardwareOpenKind, HardwareOpens, HardwareTile,
        // game mode (section 06)
        GameModePhase, GameModeChoice, WindDownKind, WindDownEffect, WindDownStatus, WindDownItem,
        RecapOutcome, RecapItem, GameModeRecap, GameModeState, StartGameModeBody, GameModeChoiceBody,
        OtherApp, OtherApps, OtherAppsPatch, OtherAppChoice,
        // claude library
        LibraryKind, LibraryItem, LibraryPlugin, LibraryMcp, LibraryHook, LibraryOutputStyle, LibrarySetup,
        ClaudeLibrary, LibraryFact, LibraryText, LibraryOpenBody,
        // vscode themes
        VsCodeTheme, VsCodeThemeTokens, VsCodeCurrentTheme,
    );
    format!(
        "// GENERATED by `cargo test -p rain-types write_single_file`. Do not edit.\n\n{body}{}",
        topic_names_ts()
    )
}

/// `export const TOPIC_NAMES = [...] as const;`, built from the `Topic` structs so that no topic
/// can exist on one side only.
fn topic_names_ts() -> String {
    let names: Vec<String> = TOPIC_NAMES
        .iter()
        .map(|name| format!("\"{name}\""))
        .collect();
    format!(
        "export const TOPIC_NAMES = [{}] as const;\n",
        names.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    /// The target file: `RAIN_TYPES_OUT` (set in `.cargo/config.toml`), else the default place.
    fn output_path() -> PathBuf {
        match std::env::var("RAIN_TYPES_OUT") {
            Ok(path) => PathBuf::from(path),
            Err(_) => {
                PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/bindings/rain-types.ts")
            }
        }
    }

    /// Writes the TypeScript file. With `RAIN_TYPES_CHECK=1` it writes nothing and fails when the
    /// file on disk differs from what the Rust types generate (line ends are ignored).
    #[test]
    fn write_single_file() {
        let text = single_file(&Config::from_env());
        let path = output_path();
        if std::env::var("RAIN_TYPES_CHECK").as_deref() == Ok("1") {
            let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
            assert_eq!(
                on_disk.replace("\r\n", "\n"),
                text,
                "{} is out of date: run `npm run types`",
                path.display()
            );
        } else {
            std::fs::create_dir_all(path.parent().expect("the output path has a folder")).unwrap();
            std::fs::write(&path, text).unwrap();
        }
    }

    #[test]
    fn generation_is_deterministic() {
        let config = Config::from_env();
        assert_eq!(single_file(&config), single_file(&config));
    }

    #[test]
    fn field_comments_are_not_copied_into_the_file() {
        let text = single_file(&Config::from_env());
        assert!(
            !text.contains("/**"),
            "use // instead of /// on the fields of generated structs"
        );
    }

    #[test]
    fn large_integers_become_number_not_bigint() {
        // Fails when `TS_RS_LARGE_INT = "number"` of .cargo/config.toml is not in effect.
        let text = single_file(&Config::from_env());
        assert!(!text.contains("bigint"));
        assert!(text.contains("seq: number"));
    }

    #[test]
    fn optional_fields_are_optional_not_nullable() {
        let text = single_file(&Config::from_env());
        assert!(
            !text.contains("| null"),
            "an optional field came out nullable"
        );
        assert!(text.contains("reason?: string"));
        assert!(text.contains("tint?: string"));
    }

    #[test]
    fn number_unions_keep_their_exact_values() {
        let text = single_file(&Config::from_env());
        assert!(text.contains("export type ResetAfterSeconds = 30 | 60 | 300;"));
        assert!(text.contains("export type CountdownSeconds = 5 | 10 | 20 | 30;"));
    }

    #[test]
    fn topic_names_come_last_as_a_const_tuple() {
        let text = single_file(&Config::from_env());
        assert!(text.ends_with(&topic_names_ts()));
        assert!(topic_names_ts().starts_with("export const TOPIC_NAMES = [\"sessions\", \"jobs\""));
    }
}
