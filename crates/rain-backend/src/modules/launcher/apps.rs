//! The app list: what Windows lists in `shell:AppsFolder`, filtered, given stable ids, a kind
//! and keywords. Section 01 6.1, 6.2 and 6.4.
//!
//! Everything here is a pure function of the raw rows and the id map, so it has no disk, no
//! clock and no Windows call. `service.rs` reads the raw rows (`AppSource`), stores them as a
//! cache and calls `build` to make the list that the screens see.

