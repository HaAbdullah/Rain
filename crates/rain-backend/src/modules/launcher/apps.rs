// ---- where the raw rows come from ----

/// Why the installed apps could not be read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceError {
    /// The Windows shell thread did not answer in time.
    ComBusy,
    /// Windows answered with an error, or the answer made no sense.
    Failed,
}

/// Where the raw rows come from. A trait, so that a test says which apps "are installed" and
/// never reads the real PC (foundation 12.2).
pub trait AppSource: Send + Sync {
    fn enumerate(&self) -> BoxFuture<'_, Result<Vec<RawApp>, SourceError>>;
}

/// The real source: the shell's own list of apps (one call, 190 to 200 ms for 125 items).
pub struct WindowsAppSource;

impl AppSource for WindowsAppSource {
    fn enumerate(&self) -> BoxFuture<'_, Result<Vec<RawApp>, SourceError>> {
        Box::pin(async {
            com::run(shell::list_apps).await.map_err(|e| match e {
                ComError::Busy | ComError::TimedOut => SourceError::ComBusy,
                ComError::Gone | ComError::Os { .. } => SourceError::Failed,
            })
        })
    }
}

// ---- rows and records ----

/// One row of the last scan: the raw item plus what Rain worked out for the cache.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Row {
    pub key: String,
    pub aumid: String,
    pub name: String,
    pub target: String,
    pub args: String,
    /// Seconds since 1970 of the program file; `None` when the target is not a file.
    pub target_mtime: Option<i64>,
}

/// One app as the rest of the module sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppRecord {
    pub id: String,
    pub key: String,
    pub aumid: String,
    pub name: String,
    pub kind: AppKind,
    /// The program file as Windows wrote it; empty for `Store` and `Other`.
    pub exe_path: String,
    /// What the shortcut passes to the program.
    pub link_args: String,
    pub keywords: Vec<String>,
    /// First 8 hex digits of the icon hash: part of the icon address, so a changed program or a
    /// new `ICON_RENDER_VERSION` gives a new address.
    pub icon_version: String,
    /// The name of the icon file in the cache folder (16 hex digits).
    pub icon_file: String,
}

impl AppRecord {
    pub fn icon(&self) -> IconRef {
        IconRef::image(
            &format!("media/app-icon/{}?v={}", self.id, self.icon_version),
            &self.name,
        )
    }
}

/// What `build` found out.
pub struct Built {
    pub apps: Vec<AppRecord>,
    /// Keys that had no entry in the id map and now have an id. `service.rs` writes these into
    /// `app-ids.toml` once.
    pub issued: Vec<Issued>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Issued {
    pub id: String,
    pub key: String,
    pub name: String,
}

// ---- the key of an app ----

/// The text that identifies an app over time (decision C3): its AUMID in lower case, or, for an
/// item whose AUMID Windows generated, its target and arguments.
pub fn key_of(aumid: &str, name: &str, target: &str, args: &str) -> String {
    let lower_aumid = aumid.to_lowercase();
    let generated = lower_aumid.starts_with("microsoft.autogenerated.");
    if !target.is_empty() && (generated || aumid.is_empty()) {
        return format!(
            "path:{}|{}",
            normalise_path(target).to_lowercase(),
            args.to_lowercase()
        );
    }
    if aumid.is_empty() {
        return format!("name:{}", name.to_lowercase());
    }
    format!("aumid:{lower_aumid}")
}

/// `/` to `\`, a leading `\\?\` removed, and `%VAR%` parts expanded from the environment.
pub fn normalise_path(raw: &str) -> String {
    let replaced = raw.replace('/', "\\");
    let without_prefix = replaced.strip_prefix("\\\\?\\").unwrap_or(&replaced);
    expand_variables(without_prefix)
}

/// Expands `%NAME%`. A name that is not set stays as written.
fn expand_variables(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find('%') {
        out.push_str(&rest[..start]);
        let after = &rest[start + 1..];
        match after.find('%') {
            Some(end) if end > 0 => match std::env::var(&after[..end]) {
                Ok(value) => {
                    out.push_str(&value);
                    rest = &after[end + 1..];
                }
                Err(_) => {
                    out.push('%');
                    rest = after;
                }
            },
            _ => {
                out.push('%');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

// ---- the filter ----

const DOCUMENT_ENDINGS: [&str; 8] = [
    ".url", ".html", ".htm", ".pdf", ".txt", ".chm", ".rtf", ".md",
];
const DOCUMENT_NAMES: [&str; 5] = [
    "readme",
    "release notes",
    "documentation",
    "user guide",
    "user manual",
];

/// Which items are not apps: web links, game links, documents, uninstallers (rules F1 to F6 of
/// section 01 6.2). Rule F7, "the user hid it", is applied by `build`, which knows the id map.
pub fn is_not_an_app(row: &Row) -> bool {
    let name = row.name.trim().to_lowercase();
    let target = row.target.to_lowercase();
    let stem = file_stem(&row.target);
    let args = row.args.to_lowercase();
    name.is_empty()
        || target.starts_with("http://")
        || target.starts_with("https://")
        || target.contains("://")
        || DOCUMENT_ENDINGS
            .iter()
            .any(|ending| target.ends_with(ending))
        || DOCUMENT_NAMES.iter().any(|word| name.contains(word))
        || name.contains("uninstall")
        || stem.starts_with("unins")
        || (stem == "msiexec" && (args.contains("/x") || args.contains("/uninstall")))
}

/// The file name without folder and extension, lower case. A `::{CLSID}` target has none.
fn file_stem(target: &str) -> String {
    if target.starts_with("::") {
        return String::new();
    }
    let normalised = target.replace('/', "\\");
    let file = normalised.rsplit('\\').next().unwrap_or_default();
    Path::new(file)
        .file_stem()
        .map(|stem| stem.to_string_lossy().to_lowercase())
        .unwrap_or_default()
}

/// `Store` when the AUMID has a `!`; `Program` when there is a file target; else `Other`.
pub fn kind_of(aumid: &str, target: &str) -> AppKind {
    if aumid.contains('!') {
        AppKind::Store
    } else if !target.is_empty() && !target.starts_with("::") {
        AppKind::Program
    } else {
        AppKind::Other
    }
}

// ---- ids ----

/// FNV-1a over the bytes of `text`, 64 bits. Not a security hash: a stable short name.
pub fn fnv1a(text: &str) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in text.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash
}

/// 32-bit FNV-1a, for the 8 hex digits of an id.
fn fnv1a_32(text: &str) -> u32 {
    let mut hash: u32 = 0x811c_9dc5;
    for byte in text.bytes() {
        hash ^= u32::from(byte);
        hash = hash.wrapping_mul(0x0100_0193);
    }
    hash
}

/// Lower-case ASCII letters and digits; every other run of characters becomes one `-`; no `-`
/// at either end; at most `max` characters.
pub fn slug(text: &str, max: usize) -> String {
    let mut out = String::new();
    let mut pending_dash = false;
    for c in text.chars() {
        if c.is_ascii_alphanumeric() {
            if pending_dash && !out.is_empty() {
                out.push('-');
            }
            pending_dash = false;
            out.push(c.to_ascii_lowercase());
        } else {
            pending_dash = true;
        }
    }
    out.truncate(max);
    out.trim_end_matches('-').to_owned()
}

/// `base` itself, or `base-2`, `base-3` ... the first that is not in `taken`.
pub fn first_free(base: &str, taken: &HashSet<String>) -> String {
    if !taken.contains(base) {
        return base.to_owned();
    }
    let mut n: u64 = 2;
    loop {
        let candidate = format!("{base}-{n}");
        if !taken.contains(&candidate) {
            return candidate;
        }
        n += 1;
    }
}

/// The id a new app gets: `app-` plus the slug of the name; a name with no ASCII letter or
/// digit uses 8 hex digits of the hash of the key.
fn new_id(name: &str, key: &str, taken: &HashSet<String>) -> String {
    let slug = slug(name, 40);
    let base = if slug.is_empty() {
        format!("app-{:08x}", fnv1a_32(key))
    } else {
        format!("app-{slug}")
    };
    first_free(&base, taken)
}

